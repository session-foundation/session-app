import { useTokenColor } from './useTokenColor'
import Svg, { Path } from 'react-native-svg'

import { SESSION_BRAND } from './brandMark'

export interface MarkProps {
  /** Height in pixels. The width follows the mark's own proportions. */
  size: number
  /** A theme token, with or without the `$`. A literal colour also works. See useTokenColor. */
  color: string
}

/** The wordmark's artwork, in its own units. */
const WORDMARK = { width: 766.2, height: 102.3 } as const

/** How wide `SessionBrand` draws at a height of `size`, for a layout that sets it beside others. */
export function sessionBrandWidth(size: number): number {
  return (size * SESSION_BRAND.width) / SESSION_BRAND.height
}

/** How wide `SessionWordmark` draws at a height of `size`. */
export function sessionWordmarkWidth(size: number): number {
  return (size * WORDMARK.width) / WORDMARK.height
}

/**
 * The looping glyph. Drawn in the accent colour, which is what makes it the brand mark.
 *
 * A path rather than an image, here and for the wordmark below: they are one-colour marks, so a
 * path costs a few hundred bytes and takes a theme token the way everything else does. A PNG
 * would need one file per colour and per density, and would still be the wrong colour in a theme
 * nobody has drawn yet. Taken from the desktop client's icon set, so the mark is identical rather
 * than similar.
 */
export function SessionBrand({ size, color }: MarkProps) {
  const fill = useTokenColor(color)
  const { width, height, path } = SESSION_BRAND
  return (
    <Svg
      width={sessionBrandWidth(size)}
      height={size}
      viewBox={`0 0 ${width} ${height}`}
      fill={fill}
    >
      <Path d={path} />
    </Svg>
  )
}

