import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

import { PUSH_ONLY_WORDS } from '#src/pushWords'

/**
 * Writes the push words, every notification's (`NOTIFICATION_WORD_SOURCES`) and the phones' own
 * (`src/pushWords.ts`), in every language of the catalogue into the native push handlers, for a
 * push that arrives before the app has ever run and handed over its own.
 *
 * The output is committed, so a build needs no Node step, and `codegen:check` is what stops it
 * drifting from the catalogue. A language carries only the words it translates; the rest fall back
 * to English, as the app's own strings do.
 */

const appRoot = join(import.meta.dirname, '..')
const KOTLIN = join(
  appRoot,
  'modules/session-push/android/src/main/java/org/getsession/push/PushWords.generated.kt',
)
const SWIFT = join(appRoot, 'modules/session-push/ios/PushWords.generated.swift')
const OBJC = join(appRoot, 'notification-service/PushWords.generated.h')

type Words = Record<string, string>
type Source = { text: string } | { one: string }
type Forms = Partial<Record<string, string>>

type ByLocale<T> = Partial<Record<string, Partial<Record<string, T>>>>

/**
 * The catalogue's generated tables, read by path: the package's own entry imports its modules
 * without extensions, which node cannot follow.
 */
const catalogue = join(appRoot, '../../packages/localization/src/localization-src/generated')
async function load<T>(file: string): Promise<T> {
  return (await import(pathToFileURL(join(catalogue, file)).href)) as T
}
const { enSimpleNoArgs: englishSimple, enPlurals: englishPlurals } = await load<{
  enSimpleNoArgs: Record<string, string>
  enPlurals: Record<string, Forms>
}>('english.ts')
const { translationsSimpleNoArgs: simple, translationsPlurals: plurals } = await load<{
  translationsSimpleNoArgs: ByLocale<string>
  translationsPlurals: ByLocale<Forms>
}>('translations.ts')
const { NOTIFICATION_WORD_SOURCES } = (await import(
  pathToFileURL(join(appRoot, '../../packages/localization/src/notificationWordSources.ts')).href
)) as { NOTIFICATION_WORD_SOURCES: Record<string, Source> }

/** Every word the native handlers read, by the name they read it by. */
const PUSH_WORDS: Record<string, Source> = { ...NOTIFICATION_WORD_SOURCES, ...PUSH_ONLY_WORDS }

/** A plural's form for one, as `tr(key, { count: 1 })` gives it in that language. */
function formForOne(forms: Forms | undefined, locale: string): string | undefined {
  if (forms === undefined) return undefined
  const form = forms[new Intl.PluralRules(locale).select(1)] ?? forms['other']
  return form?.replaceAll('{count}', '1')
}

function english(): Words {
  return Object.fromEntries(
    Object.entries(PUSH_WORDS).map(([name, from]) => {
      const word =
        'text' in from ? englishSimple[from.text] : formForOne(englishPlurals[from.one], 'en')
      if (word === undefined) throw new Error(`no English for the push word ${name}`)
      return [name, word]
    }),
  )
}

function translated(locale: string): Words {
  const words: Words = {}
  for (const [name, from] of Object.entries(PUSH_WORDS)) {
    const word =
      'text' in from ? simple[locale]?.[from.text] : formForOne(plurals[locale]?.[from.one], locale)
    if (word !== undefined) words[name] = word
  }
  return words
}

/** A Kotlin string literal: JSON's escapes are Kotlin's, but for `$`, which starts a template. */
function kotlinString(text: string): string {
  return JSON.stringify(text).replaceAll('$', '\\$')
}

function kotlinMap(words: Words, indent: string): string {
  const pairs = Object.entries(words).map(
    ([name, word]) => `${indent}  ${kotlinString(name)} to ${kotlinString(word)},`,
  )
  return `mapOf(\n${pairs.join('\n')}\n${indent})`
}

function kotlin(): string {
  const locales = [...new Set([...Object.keys(simple), ...Object.keys(plurals)])].sort()
  const tables = locales
    .map((locale) => [locale, translated(locale)] as const)
    .filter(([, words]) => Object.keys(words).length > 0)
  // One function per language rather than one literal: a single method holding every language
  // would come near the JVM's 64 KB limit on a method's code.
  const functions = tables.map(
    ([, words], at) => `  private fun l${String(at)}() = ${kotlinMap(words, '  ')}`,
  )
  const index = tables.map(([locale], at) => `      ${kotlinString(locale)} to ::l${String(at)},`)
  return `// Generated by apps/mobile/scripts/generatePushWords.ts from the translation catalogue and
// src/pushWords.ts. Do not edit: run \`pnpm codegen\`.
package org.getsession.push

internal object PushWordsGenerated {
  val ENGLISH: Map<String, String> = ${kotlinMap(english(), '  ')}

  /** Each catalogue language's translated words, by its catalogue code. */
  val BY_LOCALE: Map<String, () -> Map<String, String>> =
    mapOf(
${index.join('\n')}
    )

${functions.join('\n\n')}
}
`
}

/** Every catalogue language with any word translated, and its words. */
function translatedTables(): ReadonlyArray<readonly [string, Words]> {
  const locales = [...new Set([...Object.keys(simple), ...Object.keys(plurals)])].sort()
  return locales
    .map((locale) => [locale, translated(locale)] as const)
    .filter(([, words]) => Object.keys(words).length > 0)
}

/** A Swift or Objective-C string literal's body: the source is UTF-8, so only these are escaped. */
function cEscaped(text: string): string {
  return text
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n')
    .replaceAll('\r', '\\r')
    .replaceAll('\t', '\\t')
}

function swiftMap(words: Words, indent: string): string {
  const pairs = Object.entries(words).map(
    ([name, word]) => `${indent}  "${cEscaped(name)}": "${cEscaped(word)}",`,
  )
  return `[\n${pairs.join('\n')}\n${indent}]`
}

function swift(): string {
  const cases = translatedTables().map(
    ([locale, words]) => `    case "${locale}": return ${swiftMap(words, '    ')}`,
  )
  return `// Generated by apps/mobile/scripts/generatePushWords.ts from the translation catalogue and
// src/pushWords.ts. Do not edit: run \`pnpm codegen\`.

enum PushWordsGenerated {
  static let english: [String: String] = ${swiftMap(english(), '  ')}

  /// Each catalogue language's translated words, by its catalogue code.
  static func translated(_ code: String) -> [String: String]? {
    switch code {
${cases.join('\n')}
    default: return nil
    }
  }

  static let codes: Set<String> = [${translatedTables()
    .map(([locale]) => `"${locale}"`)
    .join(', ')}]
}
`
}

function objcMap(words: Words, indent: string): string {
  const pairs = Object.entries(words).map(
    ([name, word]) => `${indent}  @"${cEscaped(name)}": @"${cEscaped(word)}",`,
  )
  return `@{\n${pairs.join('\n')}\n${indent}}`
}

function objc(): string {
  const entries = translatedTables().map(
    ([locale, words]) => `        @"${locale}": ${objcMap(words, '        ')},`,
  )
  return `// Generated by apps/mobile/scripts/generatePushWords.ts from the translation catalogue and
// src/pushWords.ts. Do not edit: run \`pnpm codegen\`.

#import <Foundation/Foundation.h>

static NSDictionary<NSString*, NSString*>* push_words_english(void) {
    static NSDictionary* const words = ${objcMap(english(), '    ')};
    return words;
}

/// Each catalogue language's translated words, by its catalogue code.
static NSDictionary<NSString*, NSDictionary<NSString*, NSString*>*>* push_words_by_locale(void) {
    static NSDictionary* words;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
      words = @{
${entries.join('\n')}
      };
    });
    return words;
}
`
}

const outputs: ReadonlyArray<readonly [string, string]> = [
  [KOTLIN, kotlin()],
  [SWIFT, swift()],
  [OBJC, objc()],
]
const check = process.argv.includes('--check')
let stale = false
for (const [path, text] of outputs) {
  let current: string | null
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    current = null
  }
  if (current === text) continue
  if (check) {
    console.error(`${path} is out of date: run \`pnpm codegen\``)
    stale = true
  } else writeFileSync(path, text)
}
if (stale) process.exit(1)
